"""Generate numbers.tex for the presentation from ../components.json.

components.json is the single source of truth for every count in the deck. This
script reads it and writes LaTeX macros (counts, names, colours, chart tables);
presentation.tex uses only these macros for numbers derived from the graph.

    python gen_numbers.py            # writes numbers.tex next to this script

Run it before every compile.
"""
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "components.json"
OUT = HERE / "numbers.tex"

PHASE_WORD = {0: "Zero", 1: "One", 2: "Two", 3: "Three", 4: "Four"}

# Status colours are not in components.json; they are a presentation choice.
STATUS_COLOR = {
    "exists": "334155",
    "adapt": "0E7490",
    "new": "C2410C",
    "external": "CBD5E1",
}


def camel(s: str) -> str:
    """Layer/status/edge-kind id -> letters-only macro fragment."""
    return "".join(part.capitalize() for part in s.replace("_", "-").split("-"))


def hex_rgb(h: str):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def rgb_hex(rgb) -> str:
    return "".join(f"{round(max(0, min(1, c)) * 255):02X}" for c in rgb)


def luminance(rgb) -> float:
    def lin(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_on_white(rgb) -> float:
    return 1.05 / (luminance(rgb) + 0.05)


def ink(rgb, target=4.5):
    """Darken towards black until text in this colour reads on white."""
    t = 0.0
    out = rgb
    while contrast_on_white(out) < target and t < 1:
        t += 0.02
        out = tuple(c * (1 - t) for c in rgb)
    return out


def fill(rgb):
    """A light tint for node fills; colours that are already light are kept."""
    if luminance(rgb) > 0.6:
        return rgb
    return tuple(0.80 + 0.20 * c for c in rgb)


def main():
    d = json.loads(DATA.read_text(encoding="utf-8"))
    nodes, edges = d["nodes"], d["edges"]
    layers = sorted(d["layers"], key=lambda l: l["order"])
    statuses = d["statuses"]
    phases = sorted(d["phases"], key=lambda p: p["id"])
    kinds = d["edgeKinds"]

    ids = {n["id"] for n in nodes}
    dangling = [e for e in edges if e["source"] not in ids or e["target"] not in ids]
    assert not dangling, f"edges that do not resolve: {dangling}"

    by_layer = Counter(n["layer"] for n in nodes)
    by_status = Counter(n["status"] for n in nodes)
    by_phase = Counter(n["phase"] for n in nodes)
    by_ls = Counter((n["layer"], n["status"]) for n in nodes)
    by_ps = Counter((n["phase"], n["status"]) for n in nodes)
    by_kind = Counter(e["kind"] for e in edges)
    upstream_repos = {n["repo"] for n in nodes if n["layer"] == "upstream"}

    assert sum(by_layer.values()) == len(nodes) == sum(by_status.values()) == sum(by_phase.values())
    assert sum(by_kind.values()) == len(edges)

    L = []
    w = L.append
    w("% Generated by gen_numbers.py from ../components.json. Do not edit by hand.")
    w(f"% components.json version {d['version']} ({d['updated']})")
    w(f"\\newcommand{{\\JsonVersion}}{{{d['version']}}}")
    w(f"\\newcommand{{\\JsonUpdated}}{{{d['updated']}}}")
    w(f"\\newcommand{{\\NNodes}}{{{len(nodes)}}}")
    w(f"\\newcommand{{\\NEdges}}{{{len(edges)}}}")
    w(f"\\newcommand{{\\NLayers}}{{{len(layers)}}}")
    w(f"\\newcommand{{\\NPhases}}{{{len(phases)}}}")
    w(f"\\newcommand{{\\NStatuses}}{{{len(statuses)}}}")
    w(f"\\newcommand{{\\NEdgeKinds}}{{{len(kinds)}}}")
    w(f"\\newcommand{{\\NUpstreamRepos}}{{{len(upstream_repos)}}}")

    w("% per layer: count, name, colours (base, fill tint, ink for text/borders)")
    for l in layers:
        k = camel(l["id"])
        rgb = hex_rgb(l["color"])
        w(f"\\newcommand{{\\NLayer{k}}}{{{by_layer[l['id']]}}}")
        w(f"\\newcommand{{\\LayerName{k}}}{{{l['name']}}}")
        w(f"\\definecolor{{layer{k}}}{{HTML}}{{{l['color'].lstrip('#').upper()}}}")
        w(f"\\definecolor{{layer{k}Fill}}{{HTML}}{{{rgb_hex(fill(rgb))}}}")
        w(f"\\definecolor{{layer{k}Ink}}{{HTML}}{{{rgb_hex(ink(rgb))}}}")

    w("% per status")
    for s in statuses:
        k = camel(s["id"])
        w(f"\\newcommand{{\\NStatus{k}}}{{{by_status[s['id']]}}}")
        w(f"\\newcommand{{\\StatusLabel{k}}}{{{s['label']}}}")
        w(f"\\definecolor{{status{k}}}{{HTML}}{{{STATUS_COLOR[s['id']]}}}")

    w("% per phase")
    for p in phases:
        k = PHASE_WORD[p["id"]]
        w(f"\\newcommand{{\\NPhase{k}}}{{{by_phase[p['id']]}}}")
        w(f"\\newcommand{{\\PhaseName{k}}}{{{p['name']}}}")

    w("% per layer x status")
    for l in layers:
        for s in statuses:
            w(f"\\newcommand{{\\N{camel(l['id'])}{camel(s['id'])}}}{{{by_ls[(l['id'], s['id'])]}}}")

    w("% per phase x status")
    for p in phases:
        for s in statuses:
            w(f"\\newcommand{{\\NPhase{PHASE_WORD[p['id']]}{camel(s['id'])}}}{{{by_ps[(p['id'], s['id'])]}}}")

    w("% per edge kind")
    for kd in kinds:
        w(f"\\newcommand{{\\NEdge{camel(kd['id'])}}}{{{by_kind[kd['id']]}}}")

    # Chart tables for pgfplots (rows: layers bottom-to-top as in the stack).
    sids = [s["id"] for s in statuses]
    w("% chart table: layer x status (row 0 = order 0)")
    rows = ["idx,name,label," + ",".join(sids) + ",total"]
    for i, l in enumerate(layers):
        vals = [by_ls[(l["id"], s)] for s in sids]
        rows.append(f"{i},{{{l['name']}}},{{{l['name']} ({sum(vals)})}}," + ",".join(map(str, vals)) + f",{sum(vals)}")
    w("\\pgfplotstableread[col sep=comma,row sep=\\\\]{" + "\\\\".join(rows) + "\\\\}\\LayerStatusTable")
    w("% chart table: phase x status")
    rows = ["idx,name,label," + ",".join(sids) + ",total"]
    for p in phases:
        vals = [by_ps[(p["id"], s)] for s in sids]
        rows.append(f"{p['id']},{{{p['name']}}},{{{p['id']} {p['name']} ({sum(vals)})}}," + ",".join(map(str, vals)) + f",{sum(vals)}")
    w("\\pgfplotstableread[col sep=comma,row sep=\\\\]{" + "\\\\".join(rows) + "\\\\}\\PhaseStatusTable")

    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(nodes)} nodes, {len(edges)} edges, {len(L)} lines")


if __name__ == "__main__":
    main()
