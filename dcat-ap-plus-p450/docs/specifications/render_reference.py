"""Render the component reference of components-graph.md from components.json.

components.json is the single source of truth for the component graph. This script
rewrites only the text between the two reference markers, so the hand-written
sections of the specification are never touched. Run it after editing the JSON:

    python docs/specifications/render_reference.py          # rewrite in place
    python docs/specifications/render_reference.py --check  # exit 1 if out of date
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "components.json"
SPEC = HERE / "components-graph.md"
BEGIN = "<!-- BEGIN COMPONENT REFERENCE (generated by render_reference.py; do not edit by hand) -->"
END = "<!-- END COMPONENT REFERENCE -->"


def render(d):
    layers = {l["id"]: l for l in d["layers"]}
    phases = {p["id"]: p for p in d["phases"]}
    statuses = {s["id"]: s for s in d["statuses"]}
    kinds = {k["id"]: k for k in d["edgeKinds"]}
    labels = {n["id"]: n["label"] for n in d["nodes"]}
    out_edges, in_edges = defaultdict(list), defaultdict(list)
    for e in d["edges"]:
        out_edges[e["source"]].append(e)
        in_edges[e["target"]].append(e)

    def link(i):
        return f"[{labels[i]}](#{i})"

    def edge_lines(edges, end, arrow):
        by_kind = defaultdict(list)
        for e in edges:
            note = f" ({e['label']})" if e.get("label") else ""
            by_kind[e["kind"]].append(link(e[end]) + note)
        return [f"  - {arrow} *{kinds[k]['label']}*: " + ", ".join(v) for k, v in sorted(by_kind.items())]

    lines = [BEGIN, ""]
    lines.append(
        f"{len(d['nodes'])} components and {len(d['edges'])} connections, from `components.json` "
        f"version {d['version']} ({d['updated']})."
    )
    for layer in sorted(d["layers"], key=lambda l: l["order"]):
        nodes = [n for n in d["nodes"] if n["layer"] == layer["id"]]
        lines += ["", f"### {layer['order']:02d} · {layer['name']}", "", layer["description"], ""]
        lines += ["| Component | Status | Phase | Repository |", "|---|---|---|---|"]
        for n in nodes:
            lines.append(
                f"| {link(n['id'])} | {statuses[n['status']]['label']} | "
                f"{n['phase']} {phases[n['phase']]['name']} | `{n['repo']}` |"
            )
        for n in nodes:
            lines += ["", f'<a id="{n["id"]}"></a>', "", f"#### {n['label']}  `{n['id']}`", ""]
            lines.append(
                f"*{statuses[n['status']]['label']}* · phase {n['phase']} "
                f"({phases[n['phase']]['name']}) · `{n['repo']}`"
                + (f" · `{n['path']}`" if n["path"] else "")
            )
            lines += ["", n["summary"], ""]
            conn = edge_lines(in_edges[n["id"]], "source", "from") + edge_lines(
                out_edges[n["id"]], "target", "to"
            )
            if conn:
                lines += ["- Connections:"] + conn
    lines += ["", END]
    return "\n".join(lines)


def main():
    d = json.loads(DATA.read_text(encoding="utf-8"))
    spec = SPEC.read_text(encoding="utf-8")
    if BEGIN not in spec or END not in spec:
        sys.exit("reference markers not found in components-graph.md")
    head, rest = spec.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + render(d) + tail
    if "--check" in sys.argv:
        if new != spec:
            sys.exit("components-graph.md reference is out of date; run render_reference.py")
        print("reference up to date")
        return
    SPEC.write_text(new, encoding="utf-8", newline="\n")
    print(f"rendered {len(d['nodes'])} components")


if __name__ == "__main__":
    main()
