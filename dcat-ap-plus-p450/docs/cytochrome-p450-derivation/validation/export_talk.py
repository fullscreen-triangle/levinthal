"""Write the measured data the talk page draws into one compact JSON file.

    uv run python export_talk.py

Reads results/*.json (run run_all.py first) and the ionization energies from
the mendeleev database; writes cytochrome/src/data/talk/derivation.json.
"""
from __future__ import annotations

import json
import sqlite3
from pathlib import Path

import mendeleev

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT = HERE.parents[3] / "cytochrome" / "src" / "data" / "talk" / "derivation.json"


def load(name):
    return json.loads((RES / f"{name}.json").read_text(encoding="utf-8"))


db = next(Path(mendeleev.__file__).parent.rglob("elements.db"))
con = sqlite3.connect(db)
ie = sorted(con.execute("select atomic_number, ionization_energy from ionizationenergies "
                        "where ion_charge = 0 and ionization_energy is not null"))

g1, g2, g3, g4, g5, g6 = (load(n) for n in ("g1_atoms", "g2_backbone", "g3_boundary",
                                             "g4_record", "g5_fold", "g6_ligation"))
f1, f2, f3, f4 = (load(n) for n in ("f1_partial_sums", "f2_individuation", "f3_recurrence", "f4_ladders"))

entries = g5["entries"]
p450_ids = set(g2["entries"])
fold = [{"pdb": k, "n": v["N"], "rg": round(v["rg"], 2), "heme": round(v["heme_exposure"] * 100, 2),
         "buried": round(v["buried_atom_fraction"] * 100, 1), "p450": k in p450_ids}
        for k, v in entries.items()]

talk = {
    "source": "validation/results, regenerated by export_talk.py",
    "foundation": {
        "partialSums": {k: f1[k] for k in ("integer_partial_sum_violations_of_S_n_ge_n",
                                           "real_running_min_final_median", "dichotomy_commitments_for_eps")},
        "individuation": {k: f2[k] for k in ("integer", "real")},
        "recurrence": f3,
        "ladders": {k: f4[k] for k in ("final_gap", "summable_ladder_residual", "summable_closed_form_value",
                                       "exact_rational_ladders_closed")},
    },
    "atoms": {
        "ie": [[z, round(e, 3)] for z, e in ie],
        "closures": g1["predicted_closures"],
        "periodsCounted": g1["predicted_period_lengths"],
        "periodsObserved": g1["observed_period_lengths"],
        "drops": g1["six_largest_ie_drops_eV"],
        "fe": [g1["fe_ground_configuration"], g1["fe2_ion_ground_configuration"], g1["fe3_ion_ground_configuration"]],
    },
    "backbone": {**g2["raw"], "nBonds": g2["peptide_bonds"],
                 "transFraction": g2["omega_trans_within_20deg_fraction"], "cis": g2["omega_cis_count"],
                 "intermediate": g2["omega_intermediate_count"],
                 "CN": g2["peptide_CN_mean_sd"], "NCA": g2["N_CA_mean_sd"], "CAC": g2["CA_C_mean_sd"],
                 "NCACB": g2["N_CA_CB_angle_mean_sd"], "helical": g2["phi_psi_helical_fraction"],
                 "extended": g2["phi_psi_extended_fraction"]},
    "boundary": {"groups": g3["groups"], "values": g3["raw"]["values"], "profiles": g3["raw"]["profiles"],
                 "profileX0": g3["raw"]["profile_x0"], "threshold": g3["threshold"],
                 "named": {k: round(v["nterm_max_hydropathy"], 2) for k, v in g3["named"].items()}},
    "record": {"codonsPerResidue": g4["codons_per_residue"], "standardCost": g4["standard_code_cost"],
               "edges": g4["raw"]["cost_hist_edges"], "counts": g4["raw"]["cost_hist_counts"],
               "permuted": g4["permuted_codes"], "atOrBelow": g4["permuted_codes_at_or_below_standard"],
               "synonymousFraction": g4["synonymous_fraction"]},
    "fold": {"entries": fold,
             "sigma": {k: {"values": entries[k]["sigma_values"], "heme": entries[k]["sigma_heme"]}
                       for k in ("2CPP", "1TQN")}},
    "ligation": {
        "sites": [{"pdb": s["pdb"], "label": s["label"], "p450": s["p450"], "ligand": s["proximal_resname"],
                   "atom": s["proximal_atom"], "d": round(s["proximal_distance"], 3)} for s in g6["sites"]],
        "signature": {"pattern": g6["prosite_pattern"], **{k: g6["uniprot"][k] for k in (
            "p450_reviewed", "p450_match_fraction", "p450_strict_or_relaxed_fraction", "heme_non_p450_reviewed",
            "heme_non_p450_match_fraction", "heme_non_p450_strict_or_relaxed_fraction",
            "cys_from_c_terminus_median", "heme_non_p450_match_examples")}},
        "cTerm": {"bins": g6["raw"]["cys_from_c_terminus_bins"], "counts": g6["raw"]["cys_from_c_terminus_counts"]},
        "motifCheck": g6["structure_motif_check"],
        "distal": {k: g6["distal"][k] for k in ("1PHC", "2CPP")},
    },
}
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps(talk, separators=(",", ":")), encoding="utf-8")
print("wrote", OUT, f"{OUT.stat().st_size / 1024:.0f} KiB")
